export interface AdditionalPhone {
  id: string;
  label?: string;
  phone: string;
  ext?: string;
}

export interface ContactItem {
  id: string;
  orgId: string;
  orgName: string;
  roleCategory: string; // "Руководитель, курирующий данное направление", etc.
  fio: string;
  position: string;
  // Специфические поля для вкладки ЦИО:
  num?: string;            // Номер показателя (напр. "1.", "3.1.", "3.3.1.")
  indicatorName?: string;  // Наименование показателя / критерия
  cioName?: string;        // Наименование ЦИО (напр. "Минтер", "ГУРБ", "МИМП")
  isGroupHeader?: boolean; // Строка-группа без исполнителя
  // Раздельные поля телефонов для хранения в БД:
  workPhone?: string;      // Рабочий (городской) телефон
  workPhoneExt?: string;   // Добавочный номер к рабочему телефону
  mobilePhone?: string;    // Мобильный телефон
  additionalPhones?: AdditionalPhone[]; // Дополнительные телефоны
  phones?: string;         // Сводное текстовое представление
  email?: string;
}

export interface OrgGroup {
  id: string;
  num: number | string;
  name: string;
  contacts: ContactItem[];
}

/** Получение списка форматированных строк телефонов для отображения */
export function getContactPhoneLines(contact: ContactItem): string[] {
  const lines: string[] = [];

  if (contact.workPhone && contact.workPhone.trim()) {
    const ext = contact.workPhoneExt ? ` доб. ${contact.workPhoneExt.trim()}` : '';
    lines.push(`${contact.workPhone.trim()}${ext}`);
  }

  if (contact.mobilePhone && contact.mobilePhone.trim()) {
    lines.push(contact.mobilePhone.trim());
  }

  if (contact.additionalPhones && contact.additionalPhones.length > 0) {
    contact.additionalPhones.forEach((ap) => {
      if (ap.phone && ap.phone.trim()) {
        const ext = ap.ext ? ` доб. ${ap.ext.trim()}` : '';
        const label = ap.label ? ` (${ap.label})` : '';
        lines.push(`${ap.phone.trim()}${ext}${label}`);
      }
    });
  }

  // Если раздельные поля не заполнены, но есть строковое поле phones (обратная совместимость)
  if (lines.length === 0 && contact.phones) {
    return contact.phones.split(/[\n;]/).map((l) => l.trim()).filter(Boolean);
  }

  return lines;
}

