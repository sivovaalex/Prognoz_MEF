// Функция генерации состояния по умолчанию для других муниципалитетов
export function getDefaultTerritoryState(munId: string): Record<string, TerritoryApprovalState> {
  if (munId === 'm1') {
    return INITIAL_BALASHIHA_STATE;
  }
  const result: Record<string, TerritoryApprovalState> = {};
  METHODOLOGY_ROWS.forEach((r) => {
    if (r.isGroup) {
      result[r.id] = {
        status: 'approved',
        omsuComment: '',
        targetValue: '',
        cioComment: '',
      };
    } else {
      // Имитация реалистичных статусов
      const isApproved = r.id === 'row-1' || r.id === 'row-2' || r.id === 'row-3-1' || r.id === 'row-3-2';
      const isPending = r.id === 'row-3-3' || r.id === 'row-3-5';
      result[r.id] = {
        status: isApproved ? 'approved' : isPending ? 'pending_cio' : 'draft',
        omsuComment: isApproved ? 'Ознакомлено, методика согласована' : '',
        targetValue: isApproved ? 'согласовано' : '—',
        cioComment: isApproved ? 'Методика согласована отраслевым ведомством' : '',
        signedBy: isApproved || isPending ? 'Ответственный сотрудник ОМСУ' : undefined,
        signedAt: isApproved || isPending ? '02.08.2026 11:00' : undefined,
        approvedBy: isApproved ? 'Куратор отраслевого ЦИО' : undefined,
        approvedAt: isApproved ? '03.08.2026 16:45' : undefined,
      };
    }
  });
  return result;
}
